#' AMDconfigurations: Average Membership Degree and AMD curves
#'
#' @description
#' `AMDconfigurations` computes Average Membership Degree (AMD) from a
#' soft-membership matrix and constructs AMD curves over candidate numbers of
#' configurations. The AMD definition is independent of the algorithm used to
#' estimate memberships; the current curve backend uses repeated fuzzy
#' c-means. The package keeps score calculation, curve construction,
#' interpretation and final assignment as distinct operations.
#'
#' @references
#' Mendoza, M. and Araújo, M. B. (2022). Biogeography of bird and mammal
#' trophic structures. *Ecography*, 2022(5), e06289.
#' \doi{10.1111/ecog.06289}
#'
#' @keywords internal
